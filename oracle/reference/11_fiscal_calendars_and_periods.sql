 * Fiscal calendar anchors and the ledger period statuses.
 *
 * Three calendars, three different answers for the same date. 2024-01-02 is
 * period 1 of FY2024 on NA_CAL, period 1 of FY2024 on EU_CAL445 but only
 * because the 4-4-5 year started on 2024-01-01 that year, and period 10 of
 * FY2024 on APAC_APR because the APAC year began in April 2023. Anything that
 * compares 'period 1' across regions is comparing different months.
 *
 * Only the period boundaries and the holidays that matter to the payment runs
 * are seeded here; the full day-grain calendar is generated by the data volume
 * work package.
 *
 * The period status rows show the real close discipline: NA closes AP before
 * GL, EU keeps a 13th adjustment period open for the statutory audit, and APAC
 * soft-closes and then reopens - 2024-03 has been reopened twice.
 * ===================================================================== */

